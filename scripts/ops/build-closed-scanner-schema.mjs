import { createHash } from 'node:crypto';
import { readFile,writeFile } from 'node:fs/promises';
export const deliveryPath='supabase/migrations/20261102003500_closed_scanner_schema_convergence.sql';
export const manifestPath='docs/release/evidence/2026-11-02/scanner-schema-manifest.json';
const paths=['supabase/migrations/20261101155855_kyc_scanner_evaluation_receipts.sql',
  'supabase/migrations/20261101220212_kyc_scanner_service_authority.sql',
  'supabase/migrations/20261101221814_kyc_scanner_versioned_policy_claims.sql'];
const sha=text=>createHash('sha256').update(text).digest('hex');
export async function closedScannerDelivery() {
  const sources=[];
  for(const path of paths) {
    const source=(await readFile(path,'utf8')).replace(/\r\n/g,'\n');
    const file=path.split('/').at(-1);const version=file.slice(0,14);const name=file.slice(15,-4);
    // Remove ONLY the standalone outer transaction lines, never PL/pgSQL BEGIN/END bodies.
    const executedSql=source.replace(/^[ \t]*(?:begin|commit);[ \t]*$/gm,'').trim()+'\n';
    sources.push({path,version,name,sourceSha256:sha(source),executedSqlSha256:sha(executedSql),executedSql});
  }
  const header=`-- Closed scanner schema only. No production key, provider worker or personal processing.
-- One atomic DO statement executes reviewed source and only THEN records canonical versions.
-- Existing source files/receipts/spend remain unchanged. Generated by build-closed-scanner-schema.mjs.
do $xoot_scanner_convergence$
declare v_sql text; v_count integer; v_statements text[]; v_history_hash text;
begin
  perform pg_advisory_xact_lock(20261102,107);
  perform set_config('lock_timeout','5s',true);
  if to_regclass('private.kyc_quarantine_receipts') is null then
    raise exception 'Reviewed quarantine baseline required' using errcode='55000';
  end if;
  select count(*) into v_count from pg_policies where schemaname='storage' and tablename='objects'
    and policyname in ('kyc_raw_reads_closed','kyc_raw_updates_closed','kyc_raw_deletes_closed','kyc_registered_paths_no_reuse')
    and permissive='RESTRICTIVE' and roles @> array['anon','authenticated']::name[];
  if v_count<>4 then raise exception 'Raw KYC Storage guards must remain closed' using errcode='55000';end if;
  select count(*) into v_count from pg_trigger t join pg_class c on c.oid=t.tgrelid join pg_namespace n on n.oid=c.relnamespace
    where not t.tgisinternal and t.tgenabled='O' and n.nspname='public' and
    ((c.relname='xooter_applications' and t.tgname='kyc_application_clearance_required') or
     (c.relname='xooters' and t.tgname='kyc_contractor_clearance_required') or
     (c.relname='user_roles' and t.tgname='kyc_role_clearance_required'));
  if v_count<>3 then raise exception 'Verified contractor activation barriers required' using errcode='55000';end if;
  select count(*) into v_count from supabase_migrations.schema_migrations where version in ('20261101155855','20261101220212','20261101221814');
  if v_count not in (0,3) then raise exception 'Partial scanner history needs explicit reconciliation' using errcode='55000';end if;
  if v_count=0 and (to_regclass('private.kyc_scan_budget') is not null or to_regclass('private.kyc_scan_attempts') is not null
    or exists(select from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public'
      and p.proname in ('claim_kyc_scan','claim_kyc_scan_v2','authorize_kyc_scan_dispatch','finish_kyc_scan','kyc_scan_worker_authorized'))) then
    raise exception 'Unrecorded scanner objects must not be overwritten or repair-stamped' using errcode='55000';
  end if;
`;
  const blocks=sources.map(s=>`  -- ${s.path}; normalized source SHA256 ${s.sourceSha256}
  v_sql := $scanner_sql_${s.version}$${s.executedSql}$scanner_sql_${s.version}$;
  if exists(select from supabase_migrations.schema_migrations where version='${s.version}') then
    select statements into v_statements from supabase_migrations.schema_migrations where version='${s.version}';
    v_history_hash:=encode(sha256(convert_to(replace(v_statements[1],E'\\r\\n',E'\\n'),'UTF8')),'hex');
    if cardinality(v_statements)<>1 or v_history_hash is null or v_history_hash not in ('${s.sourceSha256}','${s.executedSqlSha256}') then
      raise exception 'Scanner executed-source history mismatch for ${s.version}' using errcode='55000';
    end if;
  else
    execute v_sql;
    insert into supabase_migrations.schema_migrations(version,name,statements) values('${s.version}','${s.name}',array[v_sql]);
  end if;
`).join('');
  const footer=`  if not exists(select from private.kyc_scan_budget where id and maximum=32 and used between 0 and maximum
    and not personal_documents_allowed and processing_review_reference is null) then
    raise exception 'Closed nonrenewing scanner policy required' using errcode='55000';
  end if;
  select count(*) into v_count from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public'
    and p.proname in ('claim_kyc_scan','claim_kyc_scan_v2','authorize_kyc_scan_dispatch','finish_kyc_scan','kyc_scan_worker_authorized')
    and not p.prosecdef and p.proconfig @> array['search_path=""']
    and not has_function_privilege('anon',p.oid,'execute') and not has_function_privilege('authenticated',p.oid,'execute')
    and has_function_privilege('service_role',p.oid,'execute');
  if v_count<>5 then raise exception 'Service-only scanner invoker RPC contract failed' using errcode='55000';end if;
end;
$xoot_scanner_convergence$;
`;
  return {sql:header+blocks+footer,manifest:{kind:'closed-scanner-schema-convergence',productionProcessingAllowed:false,
    productionWorkerIncluded:false,sources:sources.map(({executedSql,...rest})=>rest)}};
}
if(process.argv[1]?.endsWith('build-closed-scanner-schema.mjs')) {
  const built=await closedScannerDelivery();const manifest=JSON.stringify(built.manifest,null,2)+'\n';
  if(process.argv.includes('--check')) {
    if((await readFile(deliveryPath,'utf8')).replace(/\r\n/g,'\n')!==built.sql ||
      (await readFile(manifestPath,'utf8')).replace(/\r\n/g,'\n')!==manifest) throw new Error('Generated closed scanner source differs');
  } else {
    await writeFile(deliveryPath,built.sql,{flag:'wx'});await writeFile(manifestPath,manifest,{flag:'wx'});
  }
  console.log(JSON.stringify({path:deliveryPath,manifest:manifestPath,sources:built.manifest.sources}));
}
