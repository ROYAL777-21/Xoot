select public.assert_true(not public.xoot_consume_address_lookup('suggest'),'suggestions default off');
select public.assert_true(not public.xoot_consume_address_lookup('confirm'),'confirmation default off');
select public.assert_true(not public.xoot_consume_address_lookup('unknown'),'unknown mode denied');
select public.assert_true(not public.xoot_consume_address_lookup(null),'null mode denied');
